#!/usr/bin/env python3
"""Generate engine/pocket_params.h from the LXR firmware's Parameters.h (enum ParamEnums).

Code outside the DSP (UI, sequencer, host tools) addresses LXR sound parameters by the
firmware's own numbers without including the firmware headers (which pull in the STM32 HAL
shim). pocket_lxr.c checks a sample of these numbers against the real enum at compile time.
Adapted from CLATTER's lxr/tools/gen-param-ids.py. Run from the repository root:
    python3 tools/gen-param-header.py
"""
import pathlib, re

root = pathlib.Path(__file__).resolve().parents[1]
src = (root / 'lxr/upstream/Core/Inc/Parameters.h').read_text()
body = src[src.index('enum ParamEnums'):]
body = body[body.index('{') + 1: body.index('};')]
body = re.sub(r'/\*.*?\*/', '', body, flags=re.S)
body = re.sub(r'//[^\n]*', '', body)
names = {}
value = -1
for item in body.split(','):
    item = item.strip()
    if not item:
        continue
    if '=' in item:
        name, expr = [x.strip() for x in item.split('=')]
        value = names[expr] if expr in names else int(expr, 0)
    else:
        name = item
        value += 1
    names[name] = value

out = ['/*',
       ' * GENERATED by tools/gen-param-header.py from the LXR firmware\'s Parameters.h',
       ' * (enum ParamEnums). Do not edit by hand.',
       ' *',
       ' * Copyright (C) 2012-2026 Erica Synths; generated table (C) 2026 The CLATTER contributors.',
       ' * SPDX-License-Identifier: GPL-3.0-only',
       ' */',
       '#ifndef POCKET_PARAMS_H',
       '#define POCKET_PARAMS_H',
       '']
for n, v in names.items():
    short = n[4:] if n.startswith('PAR_') else n
    out.append(f'#define POCKET_PAR_{short} {v}')
out.append('')
out.append(f'/* Number of sound parameters (END_OF_SOUND_PARAMETERS). */')
out.append(f'#define POCKET_SOUND_PARAMS {names["END_OF_SOUND_PARAMETERS"]}')
out.append('')
out.append('#endif')
(root / 'engine/pocket_params.h').write_text('\n'.join(out) + '\n')
print(f'engine/pocket_params.h: {len(names)} names, {names["END_OF_SOUND_PARAMETERS"]} sound parameters')
