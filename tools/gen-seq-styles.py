#!/usr/bin/env python3
"""Generates seq/pocket_styles.h from browser CLATTER's rhythm styles.

  python3 tools/gen-seq-styles.py ../clatter/src/rhythm/styles.ts > seq/pocket_styles.h

CLATTER has ten kinds of track and the LXR seven triggers. Its default project plays clap and
snare on one trigger, perc on DRUM 3, fx on the cymbal (src/model/defaults.ts), so those lanes
are merged here: at each step the stronger digit, the higher ghost chance. A Euclidean lane
takes the place of a written one on its trigger.

Also writes the density curve: CLATTER's applyDensity, 1 - (1 - p) ^ (1 / k) with
k = 2 ^ ((0.5 - density) * 3.2), as a table, so the generator needs no floating point and
gives the same patterns on every platform.
"""
import re, sys

TRIGGERS = [("kick", ()), ("ltom", ()), ("htom", ("perc",)), ("snare", ("clap",)), ("cymbal", ("fx",)), ("chat", ()), ("ohat", ())]
TRACK_OF = {role: t for t, (role, extra) in enumerate(TRIGGERS) for role in (role, *extra)}

source = open(sys.argv[1]).read()
blocks = re.split(r"\n  \{\n    id: '", source)[1:]
print("/* Generated by tools/gen-seq-styles.py from CLATTER's src/rhythm/styles.ts: do not edit.")
print(" * Copyright (C) 2026 The CLATTER contributors. SPDX-License-Identifier: GPL-3.0-only */")
print("#define L(p, ghost) { p, ghost }")
print("#define E(hl, hh, ll, lh) { (hl) | (hh) << 8 | (ll) << 16 | (lh) << 24, POCKET_LANE_EUCLID }")
print("static const struct pocket_style styles[POCKET_GEN_STYLES] = {")
count = 0
for block in blocks:
    label = re.search(r"label: '([A-Z]+)'", block).group(1)
    separate = "separateKickSnare: true" in block
    fills = 0
    for role in re.search(r"fillRoles: \[([^\]]*)\]", block).group(1).replace("'", "").split(", "):
        fills |= 1 << TRACK_OF[role]
    lanes = {}
    for role, body in re.findall(r"(\w+): \{ ?((?:p|euclid): .*?) ?\},?\n", block):
        p = re.search(r"p: '([^']{16})'", body)
        ghost = re.search(r"ghost: ([\d.]+)", body)
        euclid = re.search(r"hits: \[(\d+), (\d+)\], len: \[(\d+), (\d+)\]", body)
        lanes[role] = (p.group(1) if p else None, float(ghost.group(1)) if ghost else 0, euclid.groups() if euclid else None)
    print(f'\t{{ "{label}", {int(separate)}, 0x{fills:02x}, {{')
    for primary, extra in TRIGGERS:
        roles = [r for r in (primary, *extra) if r in lanes]
        found = next((lanes[r] for r in roles if lanes[r][2]), None)
        if found:
            print(f"\t\tE({', '.join(found[2])}), /* {primary} */")
            continue
        digits, ghost = [0] * 16, 0
        for r in roles:
            ghost = max(ghost, lanes[r][1])
            for i, c in enumerate(lanes[r][0]):
                digits[i] = max(digits[i], int(c) if c != "." else 0)
        print(f"\t\tL(0x{''.join(str(d) for d in digits)}ull, {round(ghost * 100)}), /* {primary} */")
    print("\t} },")
    count += 1
print("};")
print("#undef L\n#undef E")
print(f"_Static_assert(POCKET_GEN_STYLES == {count}, \"regenerate seq/pocket_styles.h\");")
print("/* 65535 * (1 - (1 - p) ^ (1 / k)), density 0, 10 .. 100 by p 0, 1/16 .. 1 */")
print("static const uint16_t densityCurve[11][17] = {")
for d in range(11):
    k = 2 ** ((0.5 - d / 10) * 3.2)
    print("\t{ " + ", ".join(str(round(65535 * (1 - (1 - p / 16) ** (1 / k)))) for p in range(17)) + " },")
print("};")
