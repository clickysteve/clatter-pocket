#!/usr/bin/env python3
"""Generates engine/pocket_param_table.c from the LXR firmware's parameterArray_init.

  python3 tools/gen-param-table.py > engine/pocket_param_table.c

parameterArray_init is some 460 assignments, 2.5 KB of code that runs once, to fill a table of
where each sound parameter lives. The same facts fit in three bytes each: a table of offsets from
a few objects. The upstream file is included unchanged for the rest of what it holds, and
`make test` compares what the two fill in, entry by entry (test_engine_packed).
"""
import re

SOURCE = "lxr/upstream/Core/Src/Soundengine/MIDI/ParameterArray.c"
text = open(SOURCE).read()
text = text[text.index("void parameterArray_init()"):]
text = re.sub(r"/\*.*?\*/", "", re.sub(r"//.*", "", text), flags=re.S)
assert "#if" not in text, "conditional assignments: read them before trusting this"

where, types = {}, {}
for name, value in re.findall(r"parameterArray\[(\w+)\]\.ptr\s*=\s*([^;]+);", text):
    where[name] = value.strip()
for name, value in re.findall(r"parameterArray\[(\w+)\]\.type\s*=\s*(\w+)\s*;", text):
    types[name] = value
assert len(re.findall(r"\.ptr\s*=", text)) >= len(where) and where, "the assignments were not understood"

kinds = sorted(set(types.values()))
pattern = re.compile(r"^&\s*(\w+)(?:\[(\d+)\])?(?:\.(.+))?$")
bases, rows = [], []
for name, value in where.items():
    m = pattern.match(value)
    assert m, f"{name}: {value}"
    base, index, member = m.groups()
    if base not in bases:
        bases.append(base)
    rows.append((name, base, index, member))
for name in types:
    assert name in where, f"{name} has a type and no place"
assert len(bases) < 15 and len(kinds) <= 16

print("""/*
 * GENERATED by tools/gen-param-table.py from the LXR firmware's parameterArray_init. Do not edit by
 * hand. The firmware's table of where each sound parameter lives, in three bytes an entry: an
 * offset from one of a few objects, and which object and what type. The file it stands in for is
 * unchanged, and included below for the rest of what it holds.
 *
 * Copyright (C) 2012-2026 Erica Synths; generated table (C) 2026 The CLATTER contributors.
 * SPDX-License-Identifier: GPL-3.0-only
 */
#define parameterArray_init parameterArray_init_upstream
#ifdef POCKET_FM1
#include "ParameterArray_upstream.inc" /* build.sh moves it here: it is compiled only through this file */
#else
#include "../lxr/upstream/Core/Src/Soundengine/MIDI/ParameterArray.c"
#endif
#undef parameterArray_init
#include <stddef.h>

struct place {
	uint16_t offset;
	uint8_t where; /* object + 1 << 4 | type; 0: no such parameter */
} __attribute__((packed));

#define HERE(object, index, member) ((uint16_t)((index) * sizeof(object) + __builtin_offsetof(__typeof__(object), member)))
""")
print("static void* const objects[] = {")
for b in bases:
    print(f"\t(void*)&{b},")
print("};\n")
for b in bases:
    print(f'_Static_assert(sizeof({b}) <= 65536, "an offset is 16 bits");')
print(f"static const struct place places[END_OF_SOUND_PARAMETERS] = {{")
for name, base, index, member in rows:
    n, kind, i = bases.index(base), types.get(name, "0"), index or "0"
    if member is None:
        offset = f"(uint16_t)({i} * sizeof({base}[0]))"
    elif index is None:
        offset = f"(uint16_t)__builtin_offsetof(__typeof__({base}), {member})"
    else:
        offset = f"HERE({base}[0], {i}, {member})"
    print(f"\t[{name}] = {{ {offset}, ({n + 1} << 4) | {kind} }},")
print("};\n")
print("""
void parameterArray_init(void)
{
	for (unsigned p = 0; p < END_OF_SOUND_PARAMETERS; p++)
	{
		const struct place* place = &places[p];
		parameterArray[p].ptr = place->where ? (uint8_t*)objects[(place->where >> 4) - 1u] + place->offset : 0;
		parameterArray[p].type = place->where & 15u;
	}
}

#ifndef POCKET_FM1
/* What upstream's own code fills in, and what this does: the same, entry by entry. */
int pocket_param_table_differences(void)
{
	static Parameter upstream[END_OF_SOUND_PARAMETERS];
	int differences = 0;
	for (unsigned p = 0; p < END_OF_SOUND_PARAMETERS; p++) parameterArray[p].ptr = 0, parameterArray[p].type = 0;
	parameterArray_init_upstream();
	for (unsigned p = 0; p < END_OF_SOUND_PARAMETERS; p++) upstream[p] = parameterArray[p];
	parameterArray_init();
	for (unsigned p = 0; p < END_OF_SOUND_PARAMETERS; p++)
		differences += upstream[p].ptr != parameterArray[p].ptr || upstream[p].type != parameterArray[p].type;
	return differences;
}
#endif""")
